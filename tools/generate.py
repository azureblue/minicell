#!/usr/bin/env python3
"""Generate minicell's data files from the tcell v3.6.0 sources.

Inputs: the tcell files pinned by SHA-256 in SOURCES.sha256. They are
downloaded once into build/tcell and verified before use:
    key.go, attr.go, runes.go   key, modifier, attribute and rune constants
    input.go                    CSI, SS3 and Linux console key tables
    tscreen.go, vt/mode.go      output escape sequences

Outputs:
    include/minicell_tcell.h    public constants
    src/vt.h                    escape sequences written to the terminal
    src/keytables.h             escape sequences read from the keyboard

Run with `make regenerate`. Requires the Python 3 standard library and, unless
build/tcell already holds the files, network access to GitHub.
"""

import ast
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TCELL = ROOT / "build/tcell"
TCELL_URL = "https://raw.githubusercontent.com/gdamore/tcell/v3.6.0/"

GO_STRING = r'"(?:[^"\\]|\\.)*"'


def read(name):
    return (TCELL / name).read_text()


def write(path, lines):
    (ROOT / path).write_text("\n".join(lines) + "\n")


def generated_header(files):
    return [
        "/* Copyright 2026 The TCell Authors. Apache License 2.0.",
        " * Generated by tools/generate.py: converted to C from tcell v3.6.0",
        " * %s. Do not edit. */" % files,
    ]


def go_string(literal):
    """Decode a Go string literal. Go and Python escapes agree for these inputs."""
    return ast.literal_eval(literal)


def c_string(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ord(ch) < 32 or ord(ch) >= 127:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def go_block(source, start):
    """The text between `start` and the closing brace or parenthesis at column 0."""
    begin = source.index(start)
    end = re.compile(r"\n[})]\n").search(source, begin).end()
    return source[begin:end]


def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


# --- Constants: key.go, attr.go, runes.go ------------------------------------


def go_constants(source, prefix):
    """Evaluate `const ( ... )` blocks with iota. Returns the integer constants
    named prefix*, skipping internal ones (lower-case names, or defined in
    terms of lower-case names) and rune-literal aliases for physical keys."""
    values, public = {}, {}
    for block in re.findall(r"\nconst \((.*?)\n\)", source, re.S):
        lines = [line.split("//")[0].strip() for line in block.splitlines()]
        lines = [line for line in lines if line]
        implicit = None
        for iota, line in enumerate(lines):
            name, expr = re.match(r"(\w+)(?:\s+\w+)?(?:\s*=\s*(.+))?$", line).groups()
            if expr is not None:
                implicit = expr if "iota" in expr else None
            else:
                expr = implicit
            try:
                value = eval(expr, {"__builtins__": {}}, {**values, "iota": iota})
            except NameError:
                continue  # refers to a skipped constant
            if not isinstance(value, int):
                continue  # rune literal, e.g. KeyA = 'a'
            values[name] = value
            internal = re.search(r"\b(?!iota\b)[a-z]\w*", expr)
            if name.startswith(prefix) and not internal:
                public[name] = value
    return public


def generate_constants():
    key_go = read("key.go")
    keys = go_constants(key_go, "Key")
    mods = go_constants(key_go, "Mod")
    attrs = {k: v for k, v in go_constants(read("attr.go"), "Attr").items() if k != "AttrInvalid"}
    runes = {name: ord(ch) for name, ch in re.findall(r"(Rune\w+)\s*=\s*'([^']+)'", read("runes.go"))}

    lines = [
        *generated_header('key.go, attr.go and runes.go'),
        "#ifndef MINICELL_TCELL_H",
        "#define MINICELL_TCELL_H",
        "",
        "/* Key: special keys. Printable characters are MC_KeyRune with a rune. */",
        "enum {",
    ]
    lines += ["    MC_%s = %d," % item for item in keys.items()]
    lines += ["};", "", "/* ModMask: modifier key bits. */", "enum {"]
    lines += ["    MC_%s = %d," % item for item in mods.items()]
    lines += ["};", "", "/* AttrMask: text attributes. */", "enum {"]
    lines += ["    MC_%s = %d," % item for item in attrs.items()]
    lines += ["};", "", "/* Runes: line drawing and other special characters. */", "enum {"]
    lines += ["    MC_%s = 0x%04X, /* %s */" % (n, v, chr(v)) for n, v in runes.items()]
    lines += ["};", "", "#endif"]
    write("include/minicell_tcell.h", lines)


# --- Output sequences: tscreen.go, vt/mode.go --------------------------------

# tscreen.go constants that minicell writes.
SEQUENCES = ["sgr0", "bold", "dim", "italic", "underline", "blink", "reverse", "strikeThrough",
             "clear", "setCursorPosition", "setFg8", "setFg256", "setBg8", "setBg256",
             "enterCA", "exitCA", "enterKeypad", "exitKeypad"]

# Strings that tscreen.go only assigns for terminals that are not "legacy".
NON_LEGACY = ["saveTitle", "restoreTitle"]

# vt/mode.go private modes that minicell sets and resets.
MODES = ["PmShowCursor", "PmAutoMargin", "PmSyncOutput"]


def generate_sequences():
    tscreen = read("tscreen.go")
    consts = dict(re.findall(r"^\t(\w+)\s+= (%s)" % GO_STRING, tscreen, re.M))
    osc = go_block(tscreen, "func (t *tScreen) prepareExtendedOSC() {")
    assigned = dict(re.findall(r"t\.(\w+) = (%s)" % GO_STRING, osc))
    mode_go = read("vt/mode.go")
    modes = dict(re.findall(r"^\t(Pm\w+)\s+PrivateMode = (\d+)", mode_go, re.M))

    def mode_format(method):
        pattern = r"\(pm PrivateMode\) %s\(\) string \{\n\treturn fmt\.Sprintf\((%s)" % (method, GO_STRING)
        return go_string(re.search(pattern, mode_go).group(1))

    def define(name, value, source):
        return "#define VT_%-22s %-22s /* %s */" % (snake(name), c_string(value), source)

    lines = [
        *generated_header('tscreen.go and vt/mode.go'),
        "#ifndef MC_VT_H",
        "#define MC_VT_H",
        "",
    ]
    for name in SEQUENCES:
        value = go_string(consts[name])
        if name == "setCursorPosition":
            assert value == "\x1b[%[1]d;%[2]dH", value
            value = "\x1b[%d;%dH"  # row, column: Go's explicit indexes in C order
        lines.append(define(name, value, name))
    lines += ["", "/* Not sent to legacy terminals (linux, vt*, *ansi*, sun). */"]
    lines += [define(name, go_string(assigned[name]), name) for name in NON_LEGACY]
    lines.append("")
    for name in MODES:
        number = int(modes[name])
        lines.append(define(name[2:] + "On", mode_format("Enable") % number, name + ".Enable()"))
        lines.append(define(name[2:] + "Off", mode_format("Disable") % number, name + ".Disable()"))
    lines += ["", "#endif"]
    write("src/vt.h", lines)


# --- Input key tables: input.go ----------------------------------------------


def mods_expr(expr):
    return " | ".join("MC_" + m.strip() for m in expr.split("|")) if expr else "MC_ModNone"


def generate_key_tables():
    source = read("input.go")
    csi = re.findall(r"\{M: '(.)'(?:, P: (\d+))?\}:\s*\{Key: (\w+)(?:, Mod: ([\w| ]+))?\}",
                     go_block(source, "var csiAllKeys = "))
    ss3 = re.findall(r"'(.)': \{key: (\w+)(?:, str: \"(.)\")?\}", go_block(source, "var ss3Keys = "))
    linux = re.findall(r"'(.)': (Key\w+)", go_block(source, "var linuxFKeys = "))

    lines = [
        *generated_header('input.go'),
        "#ifndef MC_KEYTABLES_H",
        "#define MC_KEYTABLES_H",
        "",
        '#include "minicell.h"',
        "",
        "/* csiAllKeys: CSI <param> <final> */",
        "static const struct {",
        "    char final;",
        "    int param;",
        "    int key, mods;",
        "} csi_keys[] = {",
    ]
    for final, param, key, mods in csi:
        if key.startswith("key"):
            continue  # bracketed paste markers; paste is not supported
        lines.append("    {'%s', %s, MC_%s, %s}," % (final, param or 0, key, mods_expr(mods)))
    lines += ["};", "", "/* ss3Keys: SS3 <final>, application mode keys */", "static const struct {",
              "    char final;", "    int key;", "    char rune;", "} ss3_keys[] = {"]
    for final, key, rune in ss3:
        lines.append("    {'%s', MC_%s, %s}," % (final, key, "'%s'" % rune if rune else "0"))
    lines += ["};", "", "/* linuxFKeys: CSI [ <final>, Linux console F1-F5 */", "static const struct {",
              "    char final;", "    int key;", "} linux_keys[] = {"]
    lines += ["    {'%s', MC_%s}," % item for item in linux]
    lines += ["};", "", "#endif"]
    write("src/keytables.h", lines)


def fetch_sources():
    """Ensures build/tcell holds every pinned file with the pinned checksum."""
    for line in (ROOT / "SOURCES.sha256").read_text().splitlines():
        digest, name = line.split(None, 1)
        path = TCELL / name
        if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() == digest:
            continue
        print("Downloading", TCELL_URL + name)
        with urllib.request.urlopen(TCELL_URL + name, timeout=30) as response:
            data = response.read()
        if hashlib.sha256(data).hexdigest() != digest:
            sys.exit("%s: checksum does not match SOURCES.sha256" % name)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def main():
    fetch_sources()
    generate_constants()
    generate_sequences()
    generate_key_tables()
    print("Generated constants, escape sequences and key tables.")


if __name__ == "__main__":
    main()
